// 自己紹介や名前に「フォローを返します」と書いてあるか（フォロバ宣言）を判定する。
// 取り込みのたびに最新のプロフィールから判定し直すので、データベースには保存しない。
// 「フォロバはマイペース」「フォロバしない」のような書き方は拾わない。拾い漏れ・拾いすぎはあり得る。

const PATTERNS = [
  /フォロバ(?:率)?\s*100\s*%/, // フォロバ100%
  /follow\s*back/i, // Follow Back 100%
  /互\s*fo/i, // 互fo
  /相互フォロー/, // 相互フォローほぼ100%
  /(?:フォロバ|フォローバック|フォロー返し)を?(?:します|しています|致します|いたします|させて)/, // フォロバします
  /(?:基本的に|基本|大体|だいたい|ほぼ|全員|必ず)\s*(?:フォロバ|フォロー返し)/, // 基本フォロバ・全員フォロバ
  /フォロバ\s*返/, // フォロバ返します
  /(?:貰ったら|もらったら|頂いたら|いただいたら|されたら)[^。\n]{0,8}フォロー(?:します|返し)/, // フォローを貰ったらフォローします
];

// 当てはまった言葉を返す（なければ null）。全角の英数字や％もそろえてから調べる
export function detectFollowBack(...texts) {
  for (const raw of texts) {
    const text = String(raw ?? '').normalize('NFKC');
    for (const re of PATTERNS) {
      const m = re.exec(text);
      if (m) return m[0];
    }
  }
  return null;
}
